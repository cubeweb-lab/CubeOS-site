(function() {
    let currentLang = localStorage.getItem('cubeos-lang') || 'ru';
    const toggle = document.getElementById('lang-toggle');
    
    applyLang(currentLang);
    updateFlag(currentLang);
    
    toggle.addEventListener('click', () => {
        currentLang = currentLang === 'ru' ? 'en' : 'ru';
        localStorage.setItem('cubeos-lang', currentLang);
        applyLang(currentLang);
        updateFlag(currentLang);
    });
    
    function applyLang(lang) {
        const t = translations[lang];
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key]) {
                el.innerHTML = t[key];
            }
        });
    }
    
    function updateFlag(lang) {
        toggle.textContent = lang === 'ru' ? '🇬🇧 EN' : '🇷🇺 RU';
        toggle.title = lang === 'ru' ? 'Switch to English' : 'Переключить на русский';
    }
})();
